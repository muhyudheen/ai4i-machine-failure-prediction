"""Physics-motivated feature engineering.

The AI4I 2020 failure modes are generated by simple physical rules; these
features expose those quantities directly so that even a linear model can use
them:

* power_w            = torque [Nm] * angular speed [rad/s]  -> PWF (power outside a band)
* temp_diff_k        = process temp - air temp              -> HDF (poor heat dissipation)
* overstrain_nm_min  = tool wear [min] * torque [Nm]        -> OSF (strain above a limit)

power_w is Torque × rpm × 2π/60, i.e. the brief's "Torque × Rotational speed"
times a constant. The constant changes nothing for any model but puts the
feature in real watts, which makes the SHAP plots and operating ranges readable.

The transformer is stateless (row-wise arithmetic, nothing learned in fit), so
applying it inside the CV pipeline cannot leak information across folds.
"""
import numpy as np
import pandas as pd
from sklearn.base import BaseEstimator, TransformerMixin

ENGINEERED = ["power_w", "temp_diff_k", "overstrain_nm_min"]


def add_physics_features(X: pd.DataFrame) -> pd.DataFrame:
    X = X.copy()
    X["power_w"] = X["torque_nm"] * X["rot_speed_rpm"] * 2 * np.pi / 60
    X["temp_diff_k"] = X["process_temp_k"] - X["air_temp_k"]
    X["overstrain_nm_min"] = X["tool_wear_min"] * X["torque_nm"]
    return X


class PhysicsFeatures(BaseEstimator, TransformerMixin):
    """sklearn wrapper around add_physics_features (stateless)."""

    def fit(self, X, y=None):
        self.feature_names_in_ = np.asarray(X.columns, dtype=object)
        return self

    def transform(self, X):
        return add_physics_features(X)

    def get_feature_names_out(self, input_features=None):
        if input_features is None:
            input_features = self.feature_names_in_
        return np.asarray(list(input_features) + ENGINEERED, dtype=object)
